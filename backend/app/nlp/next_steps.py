"""Recommended next steps.

Recommendations are derived only from items extracted from the transcript (unassigned tasks,
missing or ambiguous deadlines, blockers, open questions, tentative decisions, workload), so
each one carries a rationale and the evidence of the item it is based on. They are
suggestions generated by MeetingMind, not statements made in the meeting.
"""
from __future__ import annotations

import re
from collections import Counter
from datetime import date
from typing import Optional

from ..schemas import ActionItem, Decision, NextStep, Question, Risk
from .common import evidence_for
from .preprocessing import ParsedTranscript

FOLLOW_UP_MEETING = re.compile(
    r"(?i)\b(follow[- ]up (?:meeting|call|session|sync)|(?:next|another) (?:meeting|sync|call|check-in)|"
    r"reconvene|meet again|regroup|circle back|touch base)\b"
)


def _short(text: str, n: int = 90) -> str:
    text = text.strip().rstrip(".")
    return text if len(text) <= n else text[: n - 1].rsplit(" ", 1)[0] + "…"


def recommend(
    t: ParsedTranscript,
    actions: list[ActionItem],
    decisions: list[Decision],
    risks: list[Risk],
    questions: list[Question],
    meeting_date: Optional[date],
) -> list[NextStep]:
    steps: list[NextStep] = []

    def add(text, rationale, priority, category, related, evidence):
        steps.append(
            NextStep(
                id=f"N{len(steps) + 1}",
                text=text,
                rationale=rationale,
                priority=priority,
                category=category,
                related_ids=related,
                evidence=evidence[:2],
            )
        )

    for r in [r for r in risks if r.kind == "blocker"]:
        add(
            f"Resolve the blocker: {_short(r.text)}",
            "Raised as a blocker in the meeting; dependent work cannot progress until it is cleared.",
            "high",
            "blocker",
            [r.id],
            r.evidence,
        )
    for a in actions:
        if a.owner == "Unassigned":
            add(
                f"Assign an owner{' and a deadline' if a.deadline is None else ''} for “{_short(a.description, 70)}”",
                "The task was raised but no one was clearly named or volunteered"
                + (", and no due date was given." if a.deadline is None else "."),
                "high" if a.priority == "high" else "medium",
                "ownership",
                [a.id],
                a.evidence,
            )
    for a in actions:
        if a.deadline is None and a.owner != "Unassigned":
            add(
                f"Agree a deadline for “{_short(a.description, 70)}” with {a.owner}",
                "No due date was mentioned for this task.",
                "medium" if a.priority != "low" else "low",
                "deadline",
                [a.id],
                a.evidence,
            )
        elif a.deadline is not None and a.deadline.is_ambiguous:
            add(
                f"Confirm the exact date for “{_short(a.description, 60)}” (said: “{a.deadline.text}”)",
                a.deadline.note or "The deadline wording is ambiguous or not a specific day.",
                "medium",
                "deadline",
                [a.id],
                a.deadline.evidence or a.evidence,
            )
    for r in [r for r in risks if r.kind == "risk" and r.severity == "high"]:
        add(
            f"Plan a mitigation for: {_short(r.text)}",
            "Flagged as a high-severity risk (heuristic severity based on its wording).",
            "high",
            "risk",
            [r.id],
            r.evidence,
        )
    for d in [d for d in decisions if d.status == "tentative"]:
        add(
            f"Confirm the tentative decision: {_short(d.text)}",
            "This decision was provisional or conditional in the meeting.",
            "medium",
            "decision",
            [d.id],
            d.evidence,
        )
    for q in questions:
        add(
            f"Get an answer to: {_short(q.text)}",
            "Deferred during the meeting." if q.status == "deferred" else "Raised in the meeting without a clear answer.",
            "medium",
            "question",
            [q.id],
            q.evidence,
        )

    owners = Counter(a.owner for a in actions if a.owner != "Unassigned")
    if len(actions) >= 5 and owners:
        name, count = owners.most_common(1)[0]
        if count / len(actions) >= 0.5 and len(owners) > 1:
            add(
                f"Check {name}'s workload ({count} of {len(actions)} action items)",
                "Most of the action items are assigned to one person.",
                "low",
                "workload",
                [a.id for a in actions if a.owner == name],
                [],
            )

    if meeting_date:
        upcoming = sorted(
            [a for a in actions if a.deadline and a.deadline.normalized_date and a.deadline.normalized_date >= meeting_date],
            key=lambda a: a.deadline.normalized_date,
        )
        if upcoming:
            a = upcoming[0]
            days = (a.deadline.normalized_date - meeting_date).days
            when = "today" if days == 0 else "tomorrow" if days == 1 else f"in {days} days"
            add(
                f"Prioritise “{_short(a.description, 60)}” — the earliest deadline ({a.deadline.normalized_date.isoformat()}, {when})",
                "Earliest resolved deadline among the action items.",
                "high" if days <= 2 else "medium",
                "deadline",
                [a.id],
                a.evidence,
            )

    mention = next((s for s in t.sentences if FOLLOW_UP_MEETING.search(s.text)), None)
    if mention is not None:
        add(
            "Schedule the follow-up meeting that was mentioned",
            "A follow-up meeting or check-in was referred to in the discussion.",
            "low",
            "meeting",
            [],
            evidence_for([mention]),
        )
    elif questions or any(d.status == "tentative" for d in decisions):
        add(
            "Consider a short follow-up to close the open questions and tentative decisions",
            "Open items remain after this meeting.",
            "low",
            "meeting",
            [q.id for q in questions] + [d.id for d in decisions if d.status == "tentative"],
            [],
        )

    order = {"high": 0, "medium": 1, "low": 2}
    steps.sort(key=lambda s: order[s.priority])
    for i, s in enumerate(steps, start=1):
        s.id = f"N{i}"
    return steps
