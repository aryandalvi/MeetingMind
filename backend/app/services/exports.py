"""Report exports: JSON, CSV (action items), Markdown report and PDF meeting minutes.

All exporters take the AnalysisReport exactly as the client sends it, so user edits made in
the browser (owners, deadlines, statuses, descriptions) are what ends up in the files.
"""
from __future__ import annotations

import csv
import io
import json
import os
import re
from typing import Optional
from xml.sax.saxutils import escape

from ..schemas import AnalysisReport, Deadline, Evidence

STATUS_LABEL = {"open": "Open", "in_progress": "In progress", "done": "Done", "blocked": "Blocked"}
OWNER_SOURCE_LABEL = {
    "explicit_name": "named in transcript",
    "self_commitment": "self-commitment",
    "addressed_request": "request addressed to them",
    "inferred_from_reply": "inferred from their reply",
    "unassigned": "no owner found",
    "user": "set by user",
}


def safe_filename(title: str, ext: str) -> str:
    base = re.sub(r"[^A-Za-z0-9._-]+", "_", title.strip()).strip("_")[:60] or "meeting"
    return f"MeetingMind_{base}.{ext}"


def deadline_text(d: Optional[Deadline]) -> str:
    if d is None:
        return ""
    if d.normalized_date:
        label = d.normalized_date.isoformat()
        if d.text and d.date_type != "user" and d.text.lower() != label:
            label += f" ({d.text})"
        return label
    return d.text


def _evidence_line(e: Evidence) -> str:
    who = f"{e.speaker}: " if e.speaker else ""
    ts = f"[{e.timestamp}] " if e.timestamp else ""
    return f"{ts}{who}{e.text}"


# ---------------------------------------------------------------------------- JSON
def to_json(report: AnalysisReport) -> bytes:
    return json.dumps(report.model_dump(mode="json"), indent=2, ensure_ascii=False).encode("utf-8")


# ---------------------------------------------------------------------------- CSV
def _cell(value) -> str:
    text = "" if value is None else str(value)
    # Prevent spreadsheet formula injection from transcript text.
    return "'" + text if text[:1] in ("=", "+", "-", "@", "\t", "\r") else text


def to_csv(report: AnalysisReport) -> bytes:
    buf = io.StringIO()
    writer = csv.writer(buf, quoting=csv.QUOTE_MINIMAL)
    writer.writerow([
        "id", "description", "owner", "owner_source", "status", "priority", "deadline_text", "deadline_date",
        "deadline_ambiguous", "needs_review", "review_reasons", "edited", "evidence",
    ])
    for a in report.action_items:
        d = a.deadline
        writer.writerow([_cell(x) for x in [
            a.id, a.description, a.owner, OWNER_SOURCE_LABEL.get(a.owner_source, a.owner_source),
            STATUS_LABEL.get(a.status, a.status), a.priority, d.text if d else "",
            d.normalized_date.isoformat() if d and d.normalized_date else "",
            "yes" if d and d.is_ambiguous else "no" if d else "", "yes" if a.needs_review else "no",
            "; ".join(a.review_reasons), "yes" if a.edited else "no",
            " | ".join(_evidence_line(e) for e in a.evidence),
        ]])
    return ("\ufeff" + buf.getvalue()).encode("utf-8")  # BOM so Excel detects UTF-8


# ---------------------------------------------------------------------------- Markdown
def _md(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _md_evidence(evidence: list[Evidence], limit: int = 2) -> list[str]:
    return [f"  > {_md(_evidence_line(e))}" for e in evidence[:limit]]


def to_markdown(report: AnalysisReport) -> str:
    m = report.meeting
    s = report.stats
    out: list[str] = [f"# {m.title}", ""]
    meta = [f"**Date:** {m.date.isoformat() if m.date else 'not provided'}"]
    if m.context:
        meta.append(f"**Context:** {m.context}")
    meta.append(f"**Participants:** {', '.join(p.name for p in report.people if p.is_speaker) or 'not labelled'}")
    if s.duration:
        meta.append(f"**Duration:** {s.duration}")
    out += ["  \n".join(meta), ""]
    out += [
        f"_Generated by MeetingMind on {report.generated_at}"
        + (f", last edited {report.edited_at}" if report.edited_at else "")
        + ". Items are extracted automatically; check flagged items before acting on them._",
        "",
    ]

    out += ["## Executive summary", ""]
    out += [f"- {x.text}" + (" _(weakly supported)_" if x.grounding == "weak" else "") for x in report.summary.executive] or ["- No summary available."]
    out += ["", f"_{report.summary.decision_summary}_  ", f"_{report.summary.follow_up_summary}_", ""]

    if report.summary.detailed:
        out += ["## Detailed summary", ""]
        for sec in report.summary.detailed:
            out += [f"### {sec.title}", ""] + [
                f"- {x.text}" + (" _(weakly supported)_" if x.grounding == "weak" else "") for x in sec.sentences
            ] + [""]

    if report.topics:
        out += ["## Discussion topics", ""]
        for t in report.topics:
            span = f" ({t.start_timestamp}–{t.end_timestamp})" if t.start_timestamp else ""
            out.append(f"- **{t.title}**{span} — keywords: {', '.join(t.keywords) or '—'}; speakers: {', '.join(t.speakers) or '—'}")
        out.append("")

    out += ["## Decisions", ""]
    if report.decisions:
        for d in report.decisions:
            flags = [d.status, d.kind]
            if d.is_inferred:
                flags.append("inferred")
            if d.needs_review:
                flags.append("needs review")
            out.append(f"- **{d.text}** _({', '.join(flags)})_")
            out += _md_evidence(d.evidence)
    else:
        out.append("No decisions detected.")
    out.append("")

    out += ["## Action items", ""]
    if report.action_items:
        out += ["| # | Task | Owner | Deadline | Status | Priority | Review |", "|---|---|---|---|---|---|---|"]
        for a in report.action_items:
            review = "⚠ " + "; ".join(a.review_reasons) if a.needs_review else "—"
            out.append(
                f"| {a.id} | {_md(a.description)} | {_md(a.owner)} | {_md(deadline_text(a.deadline)) or '—'} | "
                f"{STATUS_LABEL.get(a.status, a.status)} | {a.priority} | {_md(review)} |"
            )
        out += ["", "<details><summary>Action item evidence</summary>", ""]
        for a in report.action_items:
            out.append(f"- **{a.id}** {a.description}")
            out += _md_evidence(a.evidence, 3)
        out += ["", "</details>"]
    else:
        out.append("No action items detected.")
    out.append("")

    if report.deadlines:
        out += ["## Deadlines", ""]
        for d in report.deadlines:
            note = f" — {d.note}" if d.note else ""
            rel = f" (→ {d.related_action_id})" if d.related_action_id else ""
            out.append(f"- **{d.normalized_date.isoformat() if d.normalized_date else 'unresolved'}** “{d.text}”{rel}{note}")
        out.append("")

    out += ["## Risks and blockers", ""]
    if report.risks:
        for r in report.risks:
            out.append(f"- **[{r.kind}, {r.severity}]** {r.text}" + (f" — _{r.speaker}_" if r.speaker else ""))
    else:
        out.append("None detected.")
    out.append("")

    out += ["## Unresolved questions", ""]
    if report.questions:
        for q in report.questions:
            out.append(f"- {q.text} _({q.status.replace('_', ' ')}{', asked by ' + q.asked_by if q.asked_by else ''})_")
    else:
        out.append("None detected.")
    out.append("")

    if report.next_steps:
        out += ["## Recommended next steps", "", "_Suggestions generated by MeetingMind from the items above._", ""]
        for n in report.next_steps:
            out.append(f"- **[{n.priority}]** {n.text} — {n.rationale}")
        out.append("")

    if report.people:
        out += ["## People", ""]
        for p in report.people:
            if p.is_speaker:
                out.append(f"- **{p.name}** — {p.talk_share}% of words, {p.utterances} turns, {p.action_items} action item(s)")
            else:
                out.append(f"- {p.name} (mentioned {p.mentions}×)")
        out.append("")

    ents = [e for e in report.entities if e.label not in {"PERSON"}]
    if ents:
        out += ["## Entities", ""]
        groups: dict[str, list[str]] = {}
        for e in ents:
            groups.setdefault(e.label_description or e.label, []).append(e.text)
        out += [f"- **{k}:** {', '.join(v)}" for k, v in groups.items()] + [""]

    if report.keywords:
        out += ["## Keywords", "", ", ".join(k.phrase for k in report.keywords), ""]
    if report.warnings:
        out += ["## Processing notes", ""] + [f"- {w}" for w in report.warnings] + [""]
    return "\n".join(out)


# ---------------------------------------------------------------------------- PDF
_FONT_CACHE: dict[str, tuple[str, str]] = {}


def _fonts() -> tuple[str, str]:
    """Register a Unicode TTF if one is available, else fall back to Helvetica."""
    if "fonts" in _FONT_CACHE:
        return _FONT_CACHE["fonts"]
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    candidates = [
        ("C:/Windows/Fonts/segoeui.ttf", "C:/Windows/Fonts/segoeuib.ttf"),
        ("C:/Windows/Fonts/arial.ttf", "C:/Windows/Fonts/arialbd.ttf"),
        ("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"),
        ("/Library/Fonts/Arial Unicode.ttf", "/Library/Fonts/Arial Unicode.ttf"),
    ]
    result = ("Helvetica", "Helvetica-Bold")
    for regular, bold in candidates:
        if os.path.exists(regular) and os.path.exists(bold):
            try:
                pdfmetrics.registerFont(TTFont("MM-Regular", regular))
                pdfmetrics.registerFont(TTFont("MM-Bold", bold))
                result = ("MM-Regular", "MM-Bold")
                break
            except Exception:
                continue
    _FONT_CACHE["fonts"] = result
    return result


def to_pdf(report: AnalysisReport) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    regular, bold = _fonts()
    unicode_font = regular != "Helvetica"

    def t(text) -> str:
        text = "" if text is None else str(text)
        if not unicode_font:  # standard PDF fonts only cover Latin-1/cp1252
            text = text.encode("cp1252", "replace").decode("cp1252")
        return escape(text)

    violet = colors.HexColor("#6D5BD0")
    ink = colors.HexColor("#1F1B2E")
    muted = colors.HexColor("#6B6780")
    lavender = colors.HexColor("#F3F0FD")
    blush = colors.HexColor("#FBEFF3")
    line = colors.HexColor("#E4E0F0")

    h1 = ParagraphStyle("h1", fontName=bold, fontSize=20, leading=24, textColor=ink, spaceAfter=4)
    h2 = ParagraphStyle("h2", fontName=bold, fontSize=12.5, leading=16, textColor=violet, spaceBefore=12, spaceAfter=5)
    body = ParagraphStyle("body", fontName=regular, fontSize=9.5, leading=13.5, textColor=ink, alignment=TA_LEFT)
    small = ParagraphStyle("small", parent=body, fontSize=8, leading=11, textColor=muted)
    cell = ParagraphStyle("cell", parent=body, fontSize=8.5, leading=11.5)
    cell_bold = ParagraphStyle("cellb", parent=cell, fontName=bold)
    bullet = ParagraphStyle("bullet", parent=body, leftIndent=10, bulletIndent=0)

    buf = io.BytesIO()
    m = report.meeting

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setFont(regular, 7.5)
        canvas.setFillColor(muted)
        canvas.drawString(18 * mm, 10 * mm, "MeetingMind · Your meetings, made meaningful · AI-extracted minutes — verify flagged items")
        canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Page {doc.page}")
        canvas.setStrokeColor(line)
        canvas.line(18 * mm, 13 * mm, A4[0] - 18 * mm, 13 * mm)
        canvas.restoreState()

    doc = SimpleDocTemplate(
        buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=18 * mm,
        title=f"Meeting minutes — {m.title}", author="MeetingMind",
    )
    story: list = [
        Paragraph(t("MEETING MINUTES"), ParagraphStyle("eyebrow", fontName=bold, fontSize=8, textColor=violet, leading=10, spaceAfter=3)),
        Paragraph(t(m.title), h1),
    ]
    meta = [f"Date: {m.date.isoformat() if m.date else 'not provided'}"]
    speakers = [p.name for p in report.people if p.is_speaker]
    if speakers:
        meta.append("Participants: " + ", ".join(speakers))
    if report.stats.duration:
        meta.append(f"Duration: {report.stats.duration}")
    story.append(Paragraph(t("  ·  ".join(meta)), small))
    if m.context:
        story.append(Paragraph(t(f"Context: {m.context}"), small))
    edited = f" · edited {report.edited_at}" if report.edited_at else ""
    story += [Paragraph(t(f"Generated {report.generated_at}{edited}"), small), Spacer(1, 6)]

    def table(rows, widths, header_bg=lavender):
        tbl = Table(rows, colWidths=widths, repeatRows=1)
        tbl.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), header_bg),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LINEBELOW", (0, 0), (-1, -1), 0.4, line),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ]))
        return tbl

    story.append(Paragraph(t("Executive summary"), h2))
    for x in report.summary.executive or []:
        story.append(Paragraph(t(x.text), bullet, bulletText="•"))
    story.append(Spacer(1, 4))
    story.append(Paragraph(t(report.summary.decision_summary), small))
    story.append(Paragraph(t(report.summary.follow_up_summary), small))

    story.append(Paragraph(t("Decisions"), h2))
    if report.decisions:
        rows = [[Paragraph(t(h), cell_bold) for h in ("Decision", "Status", "Raised by")]]
        for d in report.decisions:
            status = d.status + (" (inferred)" if d.is_inferred else "")
            rows.append([Paragraph(t(d.text), cell), Paragraph(t(status), cell), Paragraph(t(d.speaker or "—"), cell)])
        story.append(table(rows, [110 * mm, 30 * mm, 34 * mm]))
    else:
        story.append(Paragraph(t("No decisions detected."), body))

    story.append(Paragraph(t("Action items"), h2))
    if report.action_items:
        rows = [[Paragraph(t(h), cell_bold) for h in ("#", "Task", "Owner", "Deadline", "Status")]]
        for a in report.action_items:
            desc = t(a.description) + ('  <font color="#B5577A" size="7">REVIEW</font>' if a.needs_review else "")
            rows.append([
                Paragraph(t(a.id), cell), Paragraph(desc, cell), Paragraph(t(a.owner), cell),
                Paragraph(t(deadline_text(a.deadline) or "—"), cell), Paragraph(t(STATUS_LABEL.get(a.status, a.status)), cell),
            ])
        story.append(table(rows, [11 * mm, 74 * mm, 32 * mm, 36 * mm, 21 * mm]))
    else:
        story.append(Paragraph(t("No action items detected."), body))

    if report.risks:
        story.append(Paragraph(t("Risks and blockers"), h2))
        rows = [[Paragraph(t(h), cell_bold) for h in ("Type", "Severity", "Description")]]
        for r in report.risks:
            rows.append([Paragraph(t(r.kind.title()), cell), Paragraph(t(r.severity), cell), Paragraph(t(r.text), cell)])
        story.append(table(rows, [22 * mm, 20 * mm, 132 * mm], header_bg=blush))

    if report.questions:
        story.append(Paragraph(t("Unresolved questions"), h2))
        for q in report.questions:
            story.append(Paragraph(t(f"{q.text} ({q.status.replace('_', ' ')})"), bullet, bulletText="?"))

    if report.next_steps:
        block = [Paragraph(t("Recommended next steps"), h2),
                 Paragraph(t("Suggestions generated by MeetingMind from the extracted items."), small)]
        for n in report.next_steps:
            block.append(Paragraph(t(f"[{n.priority}] {n.text}"), bullet, bulletText="→" if unicode_font else "-"))
        story.append(KeepTogether(block[:6]))
        story.extend(block[6:])

    if report.topics:
        story.append(Paragraph(t("Discussion topics"), h2))
        for tp in report.topics:
            story.append(Paragraph(f"<b>{t(tp.title)}</b> — {t(tp.summary)}", bullet, bulletText="•"))

    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()


EXPORTERS = {
    "json": (to_json, "application/json", "json"),
    "csv": (to_csv, "text/csv; charset=utf-8", "csv"),
    "markdown": (lambda r: to_markdown(r).encode("utf-8"), "text/markdown; charset=utf-8", "md"),
    "pdf": (to_pdf, "application/pdf", "pdf"),
}

